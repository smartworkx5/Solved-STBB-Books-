ARABIC_SCRIPT = re.compile(r"[\u0600-\u06FF]")


def _image_size(path):
    """(width, height) of a JPEG/PNG/GIF/SVG read from its header bytes,
    with no external dependencies; None when unreadable or unknown."""
    try:
        with open(path, "rb") as fh:
            head = fh.read(256 * 1024)
    except OSError:
        return None
    if head[:8] == b"\x89PNG\r\n\x1a\n" and len(head) >= 24:
        return struct.unpack(">II", head[16:24])
    if head[:6] in (b"GIF87a", b"GIF89a") and len(head) >= 10:
        return struct.unpack("<HH", head[6:10])
    if head[:2] == b"\xff\xd8":  # JPEG: walk segments to a SOF marker
        i = 2
        while i + 9 < len(head):
            if head[i] != 0xFF:
                i += 1
                continue
            marker = head[i + 1]
            if marker in (0xC0, 0xC1, 0xC2):
                h, w = struct.unpack(">HH", head[i + 5:i + 9])
                return (w, h)
            if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
                i += 2
                continue
            i += 2 + struct.unpack(">H", head[i + 2:i + 4])[0]
        return None
    if head[:4] == b"<svg" or head[:5] == b"<?xml":
        text = head.decode("utf-8", "ignore")
        m = re.search(r'viewBox="[\d.]+ [\d.]+ ([\d.]+) ([\d.]+)"', text)
        if m:
            return (int(float(m.group(1))), int(float(m.group(2))))
        m = re.search(r'<svg[^>]*\bwidth="(\d+)"[^>]*\bheight="(\d+)"', text)
        if m:
            return (int(m.group(1)), int(m.group(2)))
    return None


_COVER_DIM_CACHE = {}


def cover_dims(root, cover, dominant):
    """Actual cover dimensions when the file is readable locally, else the
    catalogue's dominant cover size (77 covers live only in the repo)."""
    key = str(cover)
    if key not in _COVER_DIM_CACHE:
        size = _image_size(root / str(cover).lstrip("/"))
        _COVER_DIM_CACHE[key] = size or dominant
    return _COVER_DIM_CACHE[key]


def dominant_cover_size(root, books):
    counts = Counter()
    for b in books:
        if b.get("cover"):
            size = _image_size(root / str(b["cover"]).lstrip("/"))
            if size:
                counts[size] += 1
    return counts.most_common(1)[0][0] if counts else (935, 1210)


def class_label(book):
    """Class text for titles: combined-class books carry 'Class 9–10' /
    'Class 11–12' in their entry title while cls holds only the first
    class — the entry title's own label is the truthful one."""
    m = re.match(r"Class ([\d]+(?:[–\-][\d]+)?)", str(book.get("title", "")))
    if m:
        return m.group(1).replace("-", "–")
    return str(book["cls"])


def title_base_for(book):
    return (f"Class {class_label(book)} {book['subject']} Solved Exercises "
            f"— {book['medium']} Medium")


def title_attrs(book):
    """lang/dir/font attributes for title elements. dir="rtl" + the script
    font class are added when the title text itself is Arabic-script; the
    lang attribute is set for every RTL-medium book either way (current
    catalogue titles are Latin transliterations, where dir=rtl would
    misplace punctuation)."""
    medium = book.get("medium")
    lang = LANG_CODE.get(medium)
    attrs = f' lang="{lang}"' if lang else ""
    if medium in RTL_FONT_CLASS and ARABIC_SCRIPT.search(str(book.get("title", ""))):
        attrs += f' dir="rtl" class="{RTL_FONT_CLASS[medium]}"'
    return attrs


def slugify(text):
    s = re.sub(r"[^a-z0-9]+", "-", str(text).lower())
    return re.sub(r"-+", "-", s).strip("-")


def esc(text):
    return html.escape(str(text), quote=True)


def class_range(classes):
    classes = sorted(set(classes))
    if len(classes) == 1:
        return f"Class {classes[0]}"
    return f"Classes {classes[0]} to {classes[-1]}"


def join_and(items):
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def meta_description(desc):
    desc = " ".join(str(desc).split())
    if len(desc) <= 160:
        return desc
    cut = desc[:157]
    if " " in cut:
        cut = cut[: cut.rfind(" ")]
    return cut.rstrip(" .,;:") + "..."


def find_roots():
    """Return (root, push) Paths, whichever of the two trees this run uses."""
    script_root = Path(__file__).resolve().parent.parent
    if script_root.name == "push-tree":
        push = script_root
        root = script_root.parents[1]
    else:
        root = script_root
        push = root / "upload-queue" / "push-tree"
    return root, push


def load_books(root, push):
    for candidate in (push / "assets/data/books.json",
                      root / "assets/data/books.json"):
        if candidate.exists():
            with open(candidate, encoding="utf-8") as fh:
                return json.load(fh), candidate
    raise SystemExit("books.json not found in push-tree or site root")


def extract_chrome(books_html_text):
    """Pull header, footer and head asset links out of books.html."""
    header = re.search(r"<header\b.*?</header>", books_html_text, re.S).group(0)
    footer = re.search(r"<footer\b.*?</footer>", books_html_text, re.S).group(0)
    head_bits = []
    for pattern in (
        r'<link rel="icon"[^>]*>',
        r'<link rel="apple-touch-icon"[^>]*>',
        r'<link rel="manifest"[^>]*>',
        r'<meta name="theme-color"[^>]*>',
        r'<link rel="preconnect"[^>]*>',
        r'<link href="https://fonts\.googleapis\.com[^>]*>',
        r'<link rel="stylesheet" href="/assets/css/critical\.css[^>]*>',
        r'<noscript><link rel="stylesheet" href="/assets/css/style\.css[^>]*></noscript>',
    ):
        head_bits.extend(re.findall(pattern, books_html_text))
    main_js = re.search(r'<script src="/assets/js/main\.js[^>]*></script>',
                         books_html_text)
    return header, footer, "\n".join(head_bits), (main_js.group(0) if main_js else "")


def assign_urls(live):
    """Give every live book a unique page path; colliding base URLs get
    -<book-id> appended (applies to every book in the colliding group)."""
    base = {}
    for book in live:
        bslug = BOARD_SLUG[book["board"]]
        base[book["id"]] = (
            f"/books/{bslug}/class-{book['cls']}/"
            f"{slugify(book['subject'])}-{slugify(book['medium'])}.html"
        )
    counts = defaultdict(int)
    for path in base.values():
        counts[path] += 1
    urls = {}
    for book in live:
        path = base[book["id"]]
        if counts[path] > 1:
            path = path[: -len(".html")] + f"-{book['id']}.html"
        urls[book["id"]] = path
    assert len(set(urls.values())) == len(urls), "book URL collision remains"
    return urls


def sort_key(book):
    return (str(book["subject"]).lower(), str(book["medium"]).lower(),
            str(book["title"]).lower())


