def build_class_hub(board, cls, ctx):
    bslug = BOARD_SLUG[board]
    url = f"/boards/{bslug}/class-{cls}.html"
    board_hub = f"/boards/{bslug}.html"
    books = sorted((b for b in ctx["live"]
                    if b["board"] == board and b["cls"] == cls), key=sort_key)
    coming = sorted((b for b in ctx["all"]
                     if b["board"] == board and b["cls"] == cls
                     and b["status"] != "live"),
                    key=lambda b: str(b["title"]).lower())
    subjects = sorted(set(b["subject"] for b in books))
    mediums = sorted(set(b["medium"] for b in books))
    intro = (
        f"This page lists all {len(books)} live solved books for Class {cls} "
        f"of the {board}. The Class {cls} shelf covers "
        f"{join_and(subjects)} in {join_and(mediums)} medium. Every book "
        f"below is free to read online or download as a PDF."
    )
    title_tag = f"Class {cls} {board} Solved Books | SolvedBooks.pk"
    description = meta_description(intro)

    grouped = []
    for subject in subjects:
        items = "".join(
            f'<li><a href="{ctx["urls"][b["id"]]}">{esc(b["title"])}</a></li>'
            for b in books if b["subject"] == subject)
        grouped.append(f"<h3>{esc(subject)}</h3>\n"
                       f'<ul class="link-grid">{items}</ul>')
    grouped_html = "\n".join(grouped)

    coming_html = ""
    if coming:
        items = "".join(f"<li>{esc(b['title'])}</li>" for b in coming)
        coming_html = f"<h2>Coming soon</h2>\n<ul>{items}</ul>\n"

    board_classes = sorted(set(b["cls"] for b in ctx["live"]
                               if b["board"] == board))
    nav = []
    pos = board_classes.index(cls)
    if pos > 0:
        p = board_classes[pos - 1]
        nav.append(f'<span>← Previous: <a href="/boards/{bslug}/class-{p}.html">'
                   f'Class {p} {esc(BOARD_SHORT[board])} solved books</a></span>')
    if pos < len(board_classes) - 1:
        n = board_classes[pos + 1]
        nav.append(f'<span>Next: <a href="/boards/{bslug}/class-{n}.html">'
                   f'Class {n} {esc(BOARD_SHORT[board])} solved books</a> →</span>')
    nav_html = ('<nav class="prev-next" aria-label="Previous and next class">'
                + "".join(nav) + "</nav>") if nav else ""

    crumbs = ('<p class="crumbs"><a href="/">Home</a> &rsaquo; '
              f'<a href="{board_hub}">{esc(board)}</a> &rsaquo; '
              f'<span>Class {cls}</span></p>')
    jsonld = breadcrumb_jsonld([
        ("Home", "/"), (board, board_hub), (f"Class {cls}", url)])
    body = f"""{ctx['header']}
<main id="main" class="container">
{crumbs}
<h1>Class {cls} {esc(board)} Solved Books</h1>
<p>{esc(intro)}</p>
{grouped_html}
{coming_html}{nav_html}<p class="print-note">SolvedBooks.pk is an independent study-help site and is not an official website of any textbook board.</p>
</main>
{ctx['footer']}
{ctx['main_js']}
{jsonld}
</body></html>
"""
    return (page_head(title_tag, description, url, ctx["head_bits"],
                      og_image="assets/images/og-image.jpg")
            + "\n<body>\n" + body)


def build_browse_section(ctx):
    parts = [SECTION_BEGIN,
             '<section id="browse-all">',
             "<h2>Browse all solved books</h2>"]
    for board in BOARD_ORDER:
        bslug = BOARD_SLUG[board]
        books = [b for b in ctx["live"] if b["board"] == board]
        if not books:
            continue
        parts.append(
            f'<h3><a href="/boards/{bslug}.html">{esc(board)}</a></h3>')
        for cls in sorted(set(b["cls"] for b in books)):
            parts.append(
                f'<h4><a href="/boards/{bslug}/class-{cls}.html">Class {cls} '
                f'{esc(BOARD_SHORT[board])}</a></h4>')
            items = "".join(
                f'<li><a href="{ctx["urls"][b["id"]]}">{esc(b["title"])}</a></li>'
                for b in sorted((x for x in books if x["cls"] == cls),
                                key=sort_key))
            parts.append(f'<ul class="link-grid">{items}</ul>')
    parts.append("</section>")
    parts.append(SECTION_END)
    return "\n".join(parts)


def update_books_html(text, section):
    """Insert/replace the static browse section right after the catalogue
    grid (before the Tip notice); everything else stays byte-identical."""
    if SECTION_BEGIN in text:
        text = re.sub(re.escape(SECTION_BEGIN) + r".*?" + re.escape(SECTION_END),
                      "__SECTION__", text, flags=re.S)
        return text.replace("__SECTION__", section)
    anchor = '<p class="notice">Tip: click'
    assert anchor in text, "books.html insertion anchor not found"
    return text.replace(anchor, section + "\n" + anchor, 1)


def build_sitemap(hub_urls, book_urls):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for path in CORE_SITEMAP_PATHS + hub_urls + book_urls:
        lines.append(f"<url><loc>{SITE}{path}</loc></url>")
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


def write_both(root, push, rel_path, content):
    for base in (root, push):
        dest = base / rel_path
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")


def main():
    root, push = find_roots()
    books, source = load_books(root, push)
    live = [b for b in books if b.get("status") == "live"]
    urls = assign_urls(live)

    by_board_class = defaultdict(list)
    for b in live:
        by_board_class[(b["board"], b["cls"])].append(b)

    books_html_path = root / "books.html"
    books_html_text = books_html_path.read_text(encoding="utf-8")
    header, footer, head_bits, main_js = extract_chrome(books_html_text)
    # The footer must carry the corrected all-boards brand line.
    assert "SolvedBooks.pk" in footer
    assert "Textbooks are the property of their respective boards." in footer

    title_counts = Counter(title_base_for(b) for b in live)

    ctx = {
        "all": books, "live": live, "urls": urls,
        "by_board_class": by_board_class,
        "header": header, "footer": footer,
        "head_bits": head_bits, "main_js": main_js,
        "root": root,
        "dominant_cover": dominant_cover_size(root, books),
        "title_counts": title_counts,
    }

    # 1) Book pages
    for book in live:
        rel = urls[book["id"]].lstrip("/")
        write_both(root, push, rel, build_book_page(book, urls[book["id"]], ctx))

    # 2) Hubs
    hub_urls = []
    for board in BOARD_ORDER:
        if not any(b["board"] == board for b in live):
            continue
        hub_urls.append(f"/boards/{BOARD_SLUG[board]}.html")
        write_both(root, push, hub_urls[-1].lstrip("/"),
                   build_board_hub(board, ctx))
        for cls in sorted(set(b["cls"] for b in live if b["board"] == board)):
            hub_urls.append(f"/boards/{BOARD_SLUG[board]}/class-{cls}.html")
            write_both(root, push, hub_urls[-1].lstrip("/"),
                       build_class_hub(board, cls, ctx))

    book_urls = [urls[b["id"]] for b in
                 sorted(live, key=lambda b: (BOARD_ORDER.index(b["board"]),
                                             b["cls"], sort_key(b)))]

    # 3) books.html static section (both trees, kept identical)
    section = build_browse_section(ctx)
    new_books_html = update_books_html(books_html_text, section)
    for base in (root, push):
        (base / "books.html").write_text(new_books_html, encoding="utf-8")

    # 4) Sitemap (no lastmod — books.json carries no real dates)
    write_both(root, push, "sitemap-books.xml",
               build_sitemap(hub_urls, book_urls))

    # 5) Manifest
    manifest = {
        "book_pages": book_urls,
        "hubs": hub_urls,
        "urls": hub_urls + book_urls,
        "counts": {"book_pages": len(book_urls), "hubs": len(hub_urls),
                   "live_books": len(live)},
    }
    write_both(root, push, "books-manifest.json",
               json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")

    print(f"books.json source : {source}")
    print(f"live books        : {len(live)}")
    print(f"book pages written: {len(book_urls)} (x2 trees)")
    print(f"hubs written      : {len(hub_urls)} (x2 trees)")
    print(f"sitemap <loc>     : {len(CORE_SITEMAP_PATHS) + len(hub_urls) + len(book_urls)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
